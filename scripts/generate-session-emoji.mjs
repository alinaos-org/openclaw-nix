#!/usr/bin/env node
// Generate the session icon picker's emoji catalog from Unicode's emoji-test.txt:
//
//   node scripts/generate-session-emoji.mjs <emoji-test.txt> <out.ts>
//
// Keeps the fully-qualified emoji through EMOJI_VERSION, in Unicode's order, without
// skin-tone variants or the Component group, and only those the gateway accepts as a
// session icon (the same `^\p{RGI_Emoji}$` test, on the gateway's Node). Run it with that
// Node so a newer Unicode in the generator never admits an icon the gateway rejects.
import { createHash } from "node:crypto";
import fs from "node:fs";

const EMOJI_VERSION = 16.0;
const SKIN_TONES = /[\u{1F3FB}-\u{1F3FF}]/u;
const GROUPS = {
  "Smileys & Emotion": "smileys",
  "People & Body": "people",
  "Animals & Nature": "animals",
  "Food & Drink": "food",
  "Travel & Places": "travel",
  Activities: "activities",
  Objects: "objects",
  Symbols: "symbols",
  Flags: "flags",
};

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error("usage: generate-session-emoji.mjs <emoji-test.txt> <out.ts>");
  process.exit(2);
}
const text = fs.readFileSync(input, "utf8");
const sha256 = createHash("sha256").update(text).digest("hex");
const dataVersion = text.match(/^# Version: ([\d.]+)$/mu)?.[1];
if (!dataVersion) throw new Error("emoji-test.txt has no Version line");
const accepted = new RegExp("^\\p{RGI_Emoji}$", "v");

const groups = [];
let group = null;
let subgroup = null;
let count = 0;
for (const line of text.split("\n")) {
  const g = line.match(/^# group: (.+)$/u);
  if (g) {
    const id = GROUPS[g[1]];
    group = id ? { id, lines: [] } : null;
    if (group) groups.push(group);
    subgroup = null;
    continue;
  }
  const s = line.match(/^# subgroup: (.+)$/u);
  if (s) {
    subgroup = s[1];
    continue;
  }
  if (!group || !line || line.startsWith("#")) continue;
  const m = line.match(/^[0-9A-F ]+;\s*fully-qualified\s*# (\S+) E(\d+\.\d+) (.+)$/u);
  if (!m) continue;
  const [, emoji, version, name] = m;
  if (Number(version) > EMOJI_VERSION || SKIN_TONES.test(emoji) || !accepted.test(emoji)) continue;
  if (group.lines.at(-1)?.subgroup !== subgroup) group.lines.push({ subgroup, entries: [] });
  group.lines.at(-1).entries.push(`${emoji} ${name}`);
  count++;
}
for (const id of Object.values(GROUPS)) {
  if (!groups.some((g) => g.id === id)) throw new Error(`no emoji in group ${id}`);
}

// One string per group: "@<subgroup>" lines start a subgroup, the rest are "<emoji> <name>".
// ("@" because keycap emoji start with "#" and "*".)
const body = groups
  .map((g) => {
    const lines = g.lines.flatMap((sg) => [`@${sg.subgroup}`, ...sg.entries]).join("\n");
    return `  { id: "${g.id}", data: ${JSON.stringify(lines)} },`;
  })
  .join("\n");
fs.writeFileSync(
  output,
  `// Generated by openclaw-nix scripts/generate-session-emoji.mjs from Unicode emoji-test.txt
// ${dataVersion} (sha256 ${sha256}): ${count} emoji through Emoji ${EMOJI_VERSION.toFixed(1)}, without
// skin-tone variants, each accepted by the gateway's session icon check. Do not edit.
// Unicode data: https://www.unicode.org/terms_of_use.html
export type SessionEmojiGroupId =
${Object.values(GROUPS)
  .map((id) => `  | "${id}"`)
  .join("\n")};

export const SESSION_EMOJI_COUNT = ${count};

export const SESSION_EMOJI_GROUPS: readonly { id: SessionEmojiGroupId; data: string }[] = [
${body}
];
`,
);
console.log(`${count} emoji in ${groups.length} groups (emoji-test.txt ${dataVersion}, ${sha256})`);
